// The product stage skill (eminzo-product) ships with the CLI for Claude Code and Codex, from one source:
// stamped, with each tool's command form, and installed and removed like the factory skill.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from '../cli/build.mjs';
import { ENGINE_PATH, productSkill } from '../cli/src/adapters.js';
import { install, uninstall } from '../cli/src/install.js';

const repo = fileURLToPath(new URL('..', import.meta.url));
const source = readFileSync(join(repo, '.claude/skills/eminzo-product/SKILL.md'), 'utf8');
const version = JSON.parse(readFileSync(join(repo, 'cli/package.json'), 'utf8')).version;

test('the Claude form keeps the slash commands and is stamped', () => {
  const text = productSkill(source, { version, provider: 'claude' });
  assert.match(text, /^---\nname: eminzo-product\n/);
  assert.match(text, new RegExp(`Generated by eminzo ${version.replace(/\./g, '\\.')}`));
  assert.match(text, /\/eminzo-product status/);
  assert.match(text, /`\/egm:egm-brainstorm`/);
  assert.equal(ENGINE_PATH.test(text), false);
});

test('the Codex form uses $eminzo-product and the skill picker, never Claude-only commands', () => {
  const text = productSkill(source, { version, provider: 'codex' });
  assert.match(text, /\$eminzo-product status/);
  assert.doesNotMatch(text, /\/eminzo-product|\/egm:|Read, Glob, Grep/);
  assert.match(text, /the `egm-brainstorm` skill from the skill picker/);
  assert.match(text, /`egm-review` skill \(skill picker\)/);
});

test('the source keeps the rules that make it a product stage', () => {
  for (const rule of ['never create issues', 'Functional language only', 'Never promise a date', 'you cannot be one of them', 'ask the person to approve the brief', 'eminzo show roles/intake.md']) {
    assert.ok(source.includes(rule), rule);
  }
});

test('the skill reads the map first, drafts it with `map`, and gates approval and issues on the engine', () => {
  for (const rule of ['`product_map`', '"confirmed"', '"assumed"', '## map', 'factory/product-map.md', 'only after the person says yes', '`brief_status`', '`approve_brief`', '`can_create_issues` is true', 'quote its `reason`', 'never by this skill', 'explicit words']) {
    assert.ok(source.includes(rule), rule);
  }
  assert.match(productSkill(source, { version, provider: 'claude' }), /\/eminzo-product map/);
  const codex = productSkill(source, { version, provider: 'codex' });
  assert.match(codex, /\$eminzo-product map/);
  assert.match(codex, /`brief_status`/);
  for (const text of [source, codex]) {
    for (const rule of ['gh api user --jq .login', 'never invent a login', 'quote those words back', 'tied to this exact text', 'does not prove who approved']) {
      assert.ok(text.replace(/\s+/g, ' ').includes(rule), rule);
    }
    assert.doesNotMatch(text, /keeps the approval honest/);
  }
  assert.doesNotMatch(codex, /\/eminzo-product/);
});

test('build ships both forms and install writes them; uninstall removes them', () => {
  const dist = join(mkdtempSync(join(tmpdir(), 'eminzo-product-dist-')), 'dist');
  const { adapters } = build({ out: dist });
  assert.ok(adapters.includes('claude/skills/eminzo-product/SKILL.md'));
  assert.ok(adapters.includes('agents/skills/eminzo-product/SKILL.md'));
  const home = join(mkdtempSync(join(tmpdir(), 'eminzo-product-home-')), 'home');
  mkdirSync(home, { recursive: true });
  const out = { text: '', write(s) { this.text += s; } };
  assert.equal(install({ dist, version, home, mcp: false, env: { HOME: home, PATH: '' }, out }), 0);
  assert.ok(existsSync(join(home, '.claude/skills/eminzo-product/SKILL.md')));
  assert.ok(existsSync(join(home, '.agents/skills/eminzo-product/SKILL.md')));
  assert.match(out.text, /the eminzo-factory and eminzo-product skills/);
  uninstall({ home, env: { HOME: home, PATH: '' }, out });
  assert.equal(existsSync(join(home, '.claude/skills/eminzo-product')), false, 'the folder goes too');
});
