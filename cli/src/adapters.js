// Pure: turns this repo's Claude and Codex adapters (skills and agent wrappers) into the ones the
// eminzo CLI installs at user level. The engine is the `eminzo` command, not files in the repo, so
// every `factory/bin/<command>` becomes `eminzo <command>`, the roles are embedded in the agents
// (intake and spec-writer have no Bash, and a Read outside the repo can stop for a permission), and
// the skills learn the `enable` command. A source that no longer has an expected sentence fails the
// build instead of shipping a half-rewritten adapter.
//
// The agents' sources are themselves generated here: `repoAgents` renders this repo's committed
// `.claude/agents/` and `.codex/agents/` from factory/roles/*.md, one template per provider and the
// per-role data in factory/templates/agents.json (`npm run sync-agents`; `--check` fails on drift).

/** An engine path in a prompt: what must never reach a generated adapter. */
export const ENGINE_PATH = /factory\/(bin|lib|roles|templates)\//;

/** `factory/bin/<command>` -> `eminzo <command>`. */
export const engineCommands = (text) => text.replace(/factory\/bin\/([a-z][a-z-]*)/g, 'eminzo $1');

const stamp = (version) => `Generated by eminzo ${version}; \`eminzo install\` overwrites this file, so change the engine source instead.`;

function replaceRequired(text, from, to, where) {
  if (!text.includes(from)) throw new Error(`adapter source drifted: ${where} no longer contains ${JSON.stringify(from)}`);
  return text.split(from).join(to);
}

function assertNoEnginePath(text, where) {
  const m = ENGINE_PATH.exec(text);
  if (m) {
    const line = text.slice(text.lastIndexOf('\n', m.index) + 1, text.indexOf('\n', m.index)).trim();
    throw new Error(`${where}: an engine path survived the rewrite: ${line}`);
  }
  return text;
}

/** Splits `---\n<frontmatter>\n---\n<body>`. */
function splitFrontmatter(text, where) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) throw new Error(`${where}: no frontmatter`);
  return { front: m[1], body: text.slice(m[0].length) };
}

/** Rewrites shared by both skills; each is optional because the two skills word things differently. */
function rewriteSkillPaths(text) {
  return engineCommands(text
    .split('Roles live in `factory/roles/<role>.md`:').join('Roles ship with the engine (`eminzo show roles/<role>.md` prints one):')
    .split('`factory/roles/<role>.md` body').join('role body (`eminzo show roles/<role>.md` prints it)')
    .split('`factory/templates/project.md`').join('the template that `eminzo show templates/project.md` prints')
    .split('`factory/templates/review.md`').join('the template that `eminzo show templates/review.md` prints')
    .split('and point to the role body.').join('and carry the role body.')
    .split('`.claude/agents/`').join('`~/.claude/agents/`')
    .split('`.codex/agents/`').join('`~/.codex/agents/`')
    .split('`.claude/skills/eminzo-factory/SKILL.md`').join('`~/.claude/skills/eminzo-factory/SKILL.md`'));
}

/** The section every installed skill gets: where the engine is, and the `enable` command. */
function cliSection(cmd, version) {
  return `## Installed engine (eminzo CLI)

This skill was installed by \`eminzo install\` (eminzo ${version}). The factory engine is the
\`eminzo\` command, not files in the repository: every \`eminzo <command>\` in this skill (\`eminzo job\`,
\`eminzo gate\`, \`eminzo approve\`, ...) runs the engine on the repository of the current directory.
Roles and templates ship with the engine: \`eminzo show roles/<role>.md\` and
\`eminzo show templates/project.md\` print them. The repository holds only its data:
\`factory/config.json\`, \`factory/config.local.json\`, \`factory/checks.sh\`, \`factory/project.md\`,
\`factory/jobs/\`, \`factory/board.json\` and \`.worktrees/\`.

- \`${cmd} enable\`: run \`eminzo enable\` in the repository and report its output (the pull request
  URL, or each failed check with its message). Do nothing else. It is the only command that works in a
  repository without \`factory/config.json\`. After its pull request is merged and pulled, the user runs
  \`${cmd} setup\`.
- Before any other command, when the repository has no \`factory/config.json\`, stop and tell the user
  the factory is not enabled in this repository: run \`${cmd} enable\`, merge its pull request, pull,
  then run \`${cmd} setup\`.
- When \`eminzo\` is not found, tell the user to run \`npm i -g @eminzo/factory\` and \`eminzo install\`.
  When a command answers that the installed skill and agents are from another version, tell the user
  to run \`eminzo install\`. When it answers that the engine does not satisfy the \`engine\` range in
  \`factory/config.json\`, stop and report it: the repository pins another engine version.
- \`eminzo doctor\` checks Node, git, gh, the installed adapters and this repository's engine range.

`;
}

function skill(source, { version, cmd, where }) {
  const { front, body } = splitFrontmatter(source, where);
  let head = replaceRequired(front, 'argument-hint: setup | ', 'argument-hint: enable | setup | ', where);
  head = head.replace(/^(description: .*)$/m, `$1 Run ${cmd} enable once per repository first (installed with eminzo).`);
  const first = body.indexOf('\n## ');
  if (first < 0) throw new Error(`${where}: no second-level heading to put the CLI section before`);
  const text = `---\n${head}\n---\n<!-- ${stamp(version)} -->\n${body.slice(0, first + 1)}${cliSection(cmd, version)}${body.slice(first + 1)}`;
  return assertNoEnginePath(rewriteSkillPaths(text), where);
}

/** .claude/skills/eminzo-factory/SKILL.md -> the installed Claude skill. */
export const claudeSkill = (source, { version }) => skill(source, { version, cmd: '/eminzo-factory', where: 'Claude skill' });

/** .agents/skills/eminzo-factory/SKILL.md -> the installed Codex skill. */
export const codexSkill = (source, { version }) => skill(source, { version, cmd: '$eminzo-factory', where: 'Codex skill' });

/**
 * .claude/skills/eminzo-product/SKILL.md -> the installed product stage skill, for Claude Code or Codex. One source:
 * the Codex form swaps the slash commands for Codex's `$` form and the skill picker. Every swap is required, so a
 * source that changes its wording fails the build instead of shipping a skill that names the other tool's commands.
 */
export function productSkill(source, { version, provider }) {
  const where = `${provider === 'codex' ? 'Codex' : 'Claude'} product skill`;
  const { front, body } = splitFrontmatter(source, where);
  let text = `---\n${front}\n---\n<!-- ${stamp(version)} -->\n${body}`;
  if (provider === 'codex') {
    text = replaceRequired(text, 'run Elephant-Goldfish\'s brainstorm (`/egm:egm-brainstorm`\n  in Claude Code) with their idea', 'run Elephant-Goldfish\'s brainstorm (the `egm-brainstorm` skill from the skill picker)\n  with their idea', where);
    text = replaceRequired(text, 'with Elephant-Goldfish\'s\n  `/egm:egm-review`', 'with Elephant-Goldfish\'s\n  `egm-review` skill (skill picker)', where);
    text = replaceRequired(text, 'You may read the repository (Read, Glob, Grep)', 'You may read the repository', where);
    text = replaceRequired(text, '/eminzo-product', '$eminzo-product', where);
    if (/\/egm:|\/eminzo-product/.test(text)) throw new Error(`${where}: a Claude-only command survived the rewrite`);
  }
  return assertNoEnginePath(text, where);
}

/** factory/roles/<role>.md as embedded in an agent. */
const roleText = (role) => engineCommands(role).trim();

/** .claude/agents/eminzo-<role>.md -> the installed agent: hooks call eminzo, the role is embedded. */
export function claudeAgent(source, { role, roleName, version }) {
  const where = `Claude agent ${roleName}`;
  const { front, body } = splitFrontmatter(source, where);
  const hooks = front.replace(/\\?"\$CLAUDE_PROJECT_DIR\\?"\/factory\/bin\//g, 'eminzo ');
  const intro = replaceRequired(body, `Read \`factory/roles/${roleName}.md\` and follow it exactly: it is your full role.`,
    'Your full role is below, under "Role"; follow it exactly.', where);
  const text = `---\n${hooks}\n---\n<!-- ${stamp(version)} -->\n${intro.trimEnd()}\n\n## Role\n\n${roleText(role)}\n`;
  if (/CLAUDE_PROJECT_DIR/.test(text)) throw new Error(`${where}: a hook still uses $CLAUDE_PROJECT_DIR`);
  return assertNoEnginePath(engineCommands(text), where);
}

/** .codex/agents/eminzo-<role>.toml -> the installed profile: the role is appended to developer_instructions. */
export function codexAgent(source, { role, roleName, version }) {
  const where = `Codex agent ${roleName}`;
  const body = roleText(role);
  if (body.includes("'''")) throw new Error(`${where}: the role contains ''' and cannot go in a TOML literal string`);
  let text = replaceRequired(source, `, factory/roles/${roleName}.md,`, ', your role (at the end of these instructions),', where);
  const close = text.lastIndexOf("'''");
  if (close < 0 || text.indexOf("'''") === close) throw new Error(`${where}: no ''' literal string`);
  text = `${text.slice(0, close).trimEnd()}\n\nRole:\n\n${body}\n${text.slice(close)}`;
  return assertNoEnginePath(`# ${stamp(version)}\n${engineCommands(text)}`, where);
}

// ---- Repository adapters: .claude/agents/*.md and .codex/agents/*.toml, generated from the roles ----

const FILL = /\{\{([\w-]+)\}\}/g;

/** Replaces every `{{name}}` in one pass; an unknown placeholder fails instead of reaching a prompt. */
function fill(template, vars, where) {
  return template.replace(FILL, (_, name) => {
    if (!(name in vars)) throw new Error(`${where}: no value for {{${name}}}`);
    return vars[name];
  });
}

/** `## name` blocks of factory/templates/agent-shared.md -> { name: text }. The first (comment) block is dropped. */
export function sharedFragments(text) {
  const out = {};
  for (const block of text.replace(/\r\n/g, '\n').split(/^## /m).slice(1)) {
    const nl = block.indexOf('\n');
    const name = (nl < 0 ? block : block.slice(0, nl)).trim();
    const body = nl < 0 ? '' : block.slice(nl + 1).trim();
    if (!['data-rule', 'language', 'finish'].includes(name)) throw new Error(`agent-shared.md: unexpected "## ${name}" (a fragment cannot contain a "## " line)`);
    if (name in out) throw new Error(`agent-shared.md: "## ${name}" appears twice`);
    out[name] = body;
  }
  for (const name of ['data-rule', 'language', 'finish']) if (!out[name]) throw new Error(`agent-shared.md has no "## ${name}" block`);
  return out;
}

// Optional per role: protect (Claude PreToolUse hook), nudge (Stop hook), alsoWrites (extra files it may write), mustPrint.
const FIELDS = ['description', 'codexDescription', 'tools', 'model', 'scope', 'file', 'regex', 'tokens', 'inputs', 'rules'];

function check(role, meta) {
  for (const f of FIELDS) if (meta[f] === undefined) throw new Error(`agents.json: ${role} has no "${f}"`);
  if (!['job', 'round'].includes(meta.scope)) throw new Error(`agents.json: ${role} scope must be "job" or "round"`);
  if (/\n|: | #|^[\s'"|>&*!%@`#-]|\s$/.test(meta.description)) throw new Error(`agents.json: ${role} description cannot contain a newline, ": " or " #", or start or end with a YAML indicator or space (it is written as a plain YAML scalar)`);
  if (/\n|["\\]/.test(meta.codexDescription)) throw new Error(`agents.json: ${role} codexDescription cannot contain a newline, a double quote or a backslash (it is written unescaped into a TOML string)`);
  if (/['"\\]/.test(meta.regex)) throw new Error(`agents.json: ${role} regex cannot contain quotes or backslashes (it sits in a YAML hook command)`);
}

/** The parts that change per provider only in how the output file is spelled and whether a Stop hook exists. */
function parts(role, meta, shared, { path, hookNote }) {
  const vars = { path, file: meta.file, mustPrint: meta.mustPrint ?? meta.tokens, hookNote };
  return {
    role,
    description: meta.description, codexDescription: meta.codexDescription, tools: meta.tools, model: meta.model,
    tokens: meta.tokens, inputs: meta.inputs, file: meta.file, path,
    rules: meta.rules.join('\n'),
    // Extra files a role may write next to its own (the builder's plan.md), spelled for each provider.
    'also-claude': (meta.alsoWrites ?? []).map((f) => ` and \`${f}\` in the same folder`).join(''),
    'also-codex': (meta.alsoWrites ?? []).map((f) => ` and \`${path.slice(0, path.length - meta.file.length)}${f}\``).join(''),
    'data-rule': shared['data-rule'],
    language: shared.language,
    finish: fill(shared.finish, vars, `agent-shared.md finish (${role})`),
  };
}

/** The tools the protected-tests hook watches. */
const PROTECT_MATCHER = 'Edit|Write|MultiEdit|NotebookEdit';

/** .claude/agents/eminzo-<role>.md: frontmatter (with the Stop hooks) and the thin wrapper that points to the role. */
export function repoClaudeAgent(role, meta, { claude, shared }) {
  check(role, meta);
  const folder = meta.scope === 'job' ? '<job folder>' : '<round folder>';
  const hook = (cmd) => `        - type: command\n          command: ${cmd}`;
  const stop = [];
  if (meta.nudge) stop.push(hook(`'"$CLAUDE_PROJECT_DIR"/factory/bin/nudge'`));
  stop.push(hook(`"\\"$CLAUDE_PROJECT_DIR\\"/factory/bin/ensure-output '{${meta.scope}}/${meta.file}' '${meta.regex}'"`));
  // A role with `protect` also gets a PreToolUse hook that denies edits of protected tests (Codex has no hooks).
  const pre = meta.protect ? [`  PreToolUse:\n    - matcher: ${PROTECT_MATCHER}\n      hooks:\n${hook(`'"$CLAUDE_PROJECT_DIR"/factory/bin/protect-tests'`)}`] : [];
  const hooks = [`  Stop:\n    - hooks:\n${stop.join('\n')}`, ...pre].join('\n'); // Stop stays first: the desktop parses it
  const vars = { ...parts(role, meta, shared, { path: `${folder}/${meta.file}`, hookNote: ' A stop hook checks this and will not let you finish otherwise.' }), hooks };
  return fill(claude, vars, `agent-claude.md (${role})`);
}

/** .codex/agents/eminzo-<role>.toml: the profile that reads the role, with the same rules and protocol. */
export function repoCodexAgent(role, meta, { codex, shared }) {
  check(role, meta);
  const dir = meta.scope === 'job' ? 'factory/jobs/<id>' : 'factory/jobs/<id>/round-N';
  const vars = parts(role, meta, shared, { path: `${dir}/${meta.file}`, hookNote: '' });
  const text = fill(codex, vars, `agent-codex.toml (${role})`);
  if (text.split("'''").length !== 3) throw new Error(`${role}: the generated profile must hold exactly one \'\'\' literal string`);
  return text;
}

/**
 * All repository adapters as { 'relative/path': text }.
 * @param {{ meta: object, claude: string, codex: string, shared: string }} source  parsed agents.json and the three template texts
 */
export function repoAgents({ meta, claude: claudeRaw, codex: codexRaw, shared }) {
  const claude = claudeRaw.replace(/\r\n/g, '\n');
  const codex = codexRaw.replace(/\r\n/g, '\n');
  const fragments = sharedFragments(shared);
  const out = {};
  for (const role of Object.keys(meta).sort()) {
    out[`.claude/agents/eminzo-${role}.md`] = repoClaudeAgent(role, meta[role], { claude, shared: fragments });
    out[`.codex/agents/eminzo-${role}.toml`] = repoCodexAgent(role, meta[role], { codex, shared: fragments });
  }
  return out;
}
