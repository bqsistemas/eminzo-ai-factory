// Pure: turns this repo's Claude and Codex adapters (skills and agent wrappers) into the ones the
// eminzo CLI installs at user level. The engine is the `eminzo` command, not files in the repo, so
// every `factory/bin/<command>` becomes `eminzo <command>`, the roles are embedded in the agents
// (intake and spec-writer have no Bash, and a Read outside the repo can stop for a permission), and
// the skills learn the `enable` command. A source that no longer has an expected sentence fails the
// build instead of shipping a half-rewritten adapter.

/** An engine path in a prompt: what must never reach a generated adapter. */
export const ENGINE_PATH = /factory\/(bin|lib|roles|templates)\//;

/** `factory/bin/<command>` -> `eminzo <command>`. */
export const engineCommands = (text) => text.replace(/factory\/bin\/([a-z][a-z-]*)/g, 'eminzo $1');

const stamp = (version) => `Generated by eminzo ${version}; \`eminzo install\` overwrites this file, so change the engine source instead.`;

function replaceRequired(text, from, to, where) {
  if (!text.includes(from)) throw new Error(`adapter source drifted: ${where} no longer contains ${JSON.stringify(from)}`);
  return text.split(from).join(to);
}

function assertNoEnginePath(text, where) {
  const m = ENGINE_PATH.exec(text);
  if (m) {
    const line = text.slice(text.lastIndexOf('\n', m.index) + 1, text.indexOf('\n', m.index)).trim();
    throw new Error(`${where}: an engine path survived the rewrite: ${line}`);
  }
  return text;
}

/** Splits `---\n<frontmatter>\n---\n<body>`. */
function splitFrontmatter(text, where) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) throw new Error(`${where}: no frontmatter`);
  return { front: m[1], body: text.slice(m[0].length) };
}

/** Rewrites shared by both skills; each is optional because the two skills word things differently. */
function rewriteSkillPaths(text) {
  return engineCommands(text
    .split('Roles live in `factory/roles/<role>.md`:').join('Roles ship with the engine (`eminzo show roles/<role>.md` prints one):')
    .split('`factory/roles/<role>.md` body').join('role body (`eminzo show roles/<role>.md` prints it)')
    .split('`factory/templates/project.md`').join('the template that `eminzo show templates/project.md` prints')
    .split('and point to the role body.').join('and carry the role body.')
    .split('`.claude/agents/`').join('`~/.claude/agents/`')
    .split('`.codex/agents/`').join('`~/.codex/agents/`')
    .split('`.claude/skills/eminzo-factory/SKILL.md`').join('`~/.claude/skills/eminzo-factory/SKILL.md`'));
}

/** The section every installed skill gets: where the engine is, and the `enable` command. */
function cliSection(cmd, version) {
  return `## Installed engine (eminzo CLI)

This skill was installed by \`eminzo install\` (eminzo ${version}). The factory engine is the
\`eminzo\` command, not files in the repository: every \`eminzo <command>\` in this skill (\`eminzo job\`,
\`eminzo gate\`, \`eminzo approve\`, ...) runs the engine on the repository of the current directory.
Roles and templates ship with the engine: \`eminzo show roles/<role>.md\` and
\`eminzo show templates/project.md\` print them. The repository holds only its data:
\`factory/config.json\`, \`factory/config.local.json\`, \`factory/checks.sh\`, \`factory/project.md\`,
\`factory/jobs/\`, \`factory/board.json\` and \`.worktrees/\`.

- \`${cmd} enable\`: run \`eminzo enable\` in the repository and report its output (the pull request
  URL, or each failed check with its message). Do nothing else. It is the only command that works in a
  repository without \`factory/config.json\`. After its pull request is merged and pulled, the user runs
  \`${cmd} setup\`.
- Before any other command, when the repository has no \`factory/config.json\`, stop and tell the user
  the factory is not enabled in this repository: run \`${cmd} enable\`, merge its pull request, pull,
  then run \`${cmd} setup\`.
- When \`eminzo\` is not found, tell the user to run \`npm i -g @eminzo/factory\` and \`eminzo install\`.
  When a command answers that the installed skill and agents are from another version, tell the user
  to run \`eminzo install\`. When it answers that the engine does not satisfy the \`engine\` range in
  \`factory/config.json\`, stop and report it: the repository pins another engine version.
- \`eminzo doctor\` checks Node, git, gh, the installed adapters and this repository's engine range.

`;
}

function skill(source, { version, cmd, where }) {
  const { front, body } = splitFrontmatter(source, where);
  let head = replaceRequired(front, 'argument-hint: setup | ', 'argument-hint: enable | setup | ', where);
  head = head.replace(/^(description: .*)$/m, `$1 Run ${cmd} enable once per repository first (installed with eminzo).`);
  const first = body.indexOf('\n## ');
  if (first < 0) throw new Error(`${where}: no second-level heading to put the CLI section before`);
  const text = `---\n${head}\n---\n<!-- ${stamp(version)} -->\n${body.slice(0, first + 1)}${cliSection(cmd, version)}${body.slice(first + 1)}`;
  return assertNoEnginePath(rewriteSkillPaths(text), where);
}

/** .claude/skills/eminzo-factory/SKILL.md -> the installed Claude skill. */
export const claudeSkill = (source, { version }) => skill(source, { version, cmd: '/eminzo-factory', where: 'Claude skill' });

/** .agents/skills/eminzo-factory/SKILL.md -> the installed Codex skill. */
export const codexSkill = (source, { version }) => skill(source, { version, cmd: '$eminzo-factory', where: 'Codex skill' });

/** factory/roles/<role>.md as embedded in an agent. */
const roleText = (role) => engineCommands(role).trim();

/** .claude/agents/eminzo-<role>.md -> the installed agent: hooks call eminzo, the role is embedded. */
export function claudeAgent(source, { role, roleName, version }) {
  const where = `Claude agent ${roleName}`;
  const { front, body } = splitFrontmatter(source, where);
  const hooks = front.replace(/\\?"\$CLAUDE_PROJECT_DIR\\?"\/factory\/bin\//g, 'eminzo ');
  const intro = replaceRequired(body, `Read \`factory/roles/${roleName}.md\` and follow it exactly: it is your full role.`,
    'Your full role is below, under "Role"; follow it exactly.', where);
  const text = `---\n${hooks}\n---\n<!-- ${stamp(version)} -->\n${intro.trimEnd()}\n\n## Role\n\n${roleText(role)}\n`;
  if (/CLAUDE_PROJECT_DIR/.test(text)) throw new Error(`${where}: a hook still uses $CLAUDE_PROJECT_DIR`);
  return assertNoEnginePath(engineCommands(text), where);
}

/** .codex/agents/eminzo-<role>.toml -> the installed profile: the role is appended to developer_instructions. */
export function codexAgent(source, { role, roleName, version }) {
  const where = `Codex agent ${roleName}`;
  const body = roleText(role);
  if (body.includes("'''")) throw new Error(`${where}: the role contains ''' and cannot go in a TOML literal string`);
  let text = replaceRequired(source, `, factory/roles/${roleName}.md,`, ', your role (at the end of these instructions),', where);
  const close = text.lastIndexOf("'''");
  if (close < 0 || text.indexOf("'''") === close) throw new Error(`${where}: no ''' literal string`);
  text = `${text.slice(0, close).trimEnd()}\n\nRole:\n\n${body}\n${text.slice(close)}`;
  return assertNoEnginePath(`# ${stamp(version)}\n${engineCommands(text)}`, where);
}
